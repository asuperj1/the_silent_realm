// ==================== 导出函数 ====================

/**
 * 获取世界规则（始终挂载）
 */
function getWorldRules() {
  return WORLD_RULES.trim();
}

/**
 * 根据当前车厢获取定向知识
 * @param {string} currentCar - 当前车厢 ID（如 car_3_luggage）
 * @returns {string} 该车厢的完整设定文本
 */
function getCarKnowledge(currentCar) {
  if (!currentCar) return '';
  return (CAR_KNOWLEDGE[currentCar] || '').trim();
}

/**
 * 获取相邻车厢知识（玩家可能前往的区域，2格范围内）
 * @param {string} currentCar - 当前车厢 ID
 * @returns {string} 相邻车厢设定摘要
 */
function getAdjacentCarKnowledge(currentCar) {
  const carOrder = ['car_1_cab', 'car_2_economy', 'car_3_luggage', 'car_4_dining', 'car_5_sleeper', 'car_6_mail', 'car_7_service', 'car_8_cabin'];
  const idx = carOrder.indexOf(currentCar);
  if (idx < 0) return '';

  const adjacent = [];
  if (idx > 0) adjacent.push(carOrder[idx - 1]);
  if (idx < carOrder.length - 1) adjacent.push(carOrder[idx + 1]);

  return adjacent
    .map(car => {
      const knowledge = CAR_KNOWLEDGE[car];
      if (!knowledge) return '';
      // 只取首行（车厢名称+环境描述）作为摘要
      const lines = knowledge.trim().split('\n');
      return lines.slice(0, 3).join('\n');
    })
    .filter(Boolean)
    .join('\n\n');
}

/**
 * 获取陈慧 NPC 知识
 */
function getNpcChenHui() {
  return NPC_CHENHUI.trim();
}

/**
 * 获取彩蛋分支知识
 */
function getEasterEggs() {
  return EASTER_EGGS.trim();
}

/**
 * 获取所有车厢 ID 列表
 */
function getAllCarIds() {
  return Object.keys(CAR_KNOWLEDGE);
}

